#' Render a standalone HTML report for an analysis result list
#'
#' Produces a self-contained HTML document with the result list's
#' key data frames inlined as styled tables — no external dependencies
#' beyond base R + xtable / utils. The HTML is printable to PDF from the
#' browser and embeds a timestamp + the supplied settings dict so the
#' report is a faithful audit artifact for the analysis run.
#'
#' Designed to be called from inside a downloadHandler's
#' `content = function(file)`; writes directly to \code{file}.
#'
#' @param result Analysis result list (e.g. from tumor_growth_statistics).
#' @param title Title shown at the top of the report.
#' @param settings Named list of run settings to include in the metadata
#'   block (model_type, transform, reference_group, etc.).
#' @param file Output path.
#' @keywords internal
build_html_report <- function(result, title, settings, file) {
  esc <- function(x) {
    if (is.null(x)) return("")
    xc <- as.character(x)
    xc <- gsub("&", "&amp;", xc, fixed = TRUE)
    xc <- gsub("<", "&lt;",  xc, fixed = TRUE)
    xc <- gsub(">", "&gt;",  xc, fixed = TRUE)
    paste(xc, collapse = ", ")
  }
  df_to_html <- function(df, caption = NULL) {
    if (is.null(df)) return("<p><em>(not available)</em></p>")
    df <- tryCatch(as.data.frame(df), error = function(e) NULL)
    if (is.null(df) || nrow(df) == 0L) {
      return("<p><em>(empty)</em></p>")
    }
    df <- format_df_for_display(df)
    header <- paste0(
      "<tr>",
      # R20.D15: esc() collapses a vector into one string, so every header
      # landed in a single <th>. Escape each name on its own.
      paste0("<th>", vapply(colnames(df), esc, character(1L)), "</th>", collapse = ""),
      "</tr>"
    )
    rows <- vapply(seq_len(nrow(df)), function(i) {
      cells <- vapply(seq_len(ncol(df)),
                      function(j) esc(df[i, j]),
                      character(1L))
      paste0("<tr>", paste0("<td>", cells, "</td>", collapse = ""), "</tr>")
    }, character(1L))
    paste0(
      if (!is.null(caption)) paste0("<p class=\"caption\">", esc(caption), "</p>") else "",
      "<table><thead>", header, "</thead><tbody>",
      paste(rows, collapse = ""),
      "</tbody></table>"
    )
  }

  settings_html <- if (length(settings) > 0L) {
    items <- vapply(names(settings), function(k) {
      sprintf("<li><strong>%s:</strong> %s</li>", esc(k), esc(settings[[k]]))
    }, character(1L))
    paste0("<ul>", paste(items, collapse = ""), "</ul>")
  } else "<p><em>(no settings supplied)</em></p>"

  html <- paste0(
    "<!doctype html><html><head>",
    "<meta charset=\"utf-8\">",
    "<title>", esc(title), "</title>",
    "<style>",
    "body { font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', Helvetica, Arial, sans-serif; ",
    "       max-width: 1100px; margin: 20px auto; padding: 0 16px; color: #222; }",
    "h1 { color: #2166AC; border-bottom: 2px solid #2166AC; padding-bottom: 6px; }",
    "h2 { color: #444; margin-top: 28px; border-bottom: 1px solid #ddd; padding-bottom: 4px; }",
    "table { border-collapse: collapse; margin: 8px 0; font-size: 0.9em; ",
    "        width: 100%; }",
    "th, td { border: 1px solid #ccc; padding: 6px 10px; text-align: left; }",
    "thead { background: #f5f5f5; }",
    "tbody tr:nth-child(even) { background: #fafafa; }",
    ".meta { background: #f8f9fa; border-left: 4px solid #2166AC; padding: 8px 14px; ",
    "        margin: 12px 0; font-size: 0.9em; }",
    ".caption { font-style: italic; color: #666; margin: 12px 0 4px 0; }",
    "footer { color: #999; margin-top: 40px; font-size: 0.8em; ",
    "         border-top: 1px solid #ddd; padding-top: 10px; }",
    "</style></head><body>",
    "<h1>", esc(title), "</h1>",
    "<div class=\"meta\">",
    "<strong>Generated:</strong> ",
    format(Sys.time(), "%Y-%m-%d %H:%M:%S %Z"), "<br>",
    "<strong>Settings used:</strong>",
    settings_html,
    "</div>",
    "<h2>Treatment Effects</h2>",
    df_to_html(result$treatment_effects),
    "<h2>Pairwise Comparisons</h2>",
    df_to_html(result$pairwise_comparisons),
    "<h2>ANOVA</h2>",
    df_to_html(result$anova),
    "<h2>Growth Rates (per animal)</h2>",
    df_to_html(result$growth_rates),
    "<h2>Data Summary</h2>",
    df_to_html(result$data_summary),
    "<footer>Generated by the mouseExperiment dashboard. ",
    "Print to PDF from your browser to attach to a manuscript or audit trail.",
    "</footer>",
    "</body></html>"
  )
  writeLines(html, file)
  invisible(file)
}

#' The settings that produced a tumour-growth result -- R20.D46
#'
#' The report read the sidebar when it was downloaded, so a dropdown changed
#' after the run put "model_type: auc, transform: sqrt, reference_group:
#' Drug_B" above LME4 / log / Vehicle tables. The settings now come from what
#' the backend reports about the run, then from the snapshot taken when the
#' run started (`result$run_settings`).
#'
#' @param res A tumour-growth result as stored in `rv$tg_results`.
#' @return A named list for [build_html_report()].
#' @keywords internal
tg_report_settings <- function(res) {
  rs <- res$run_settings %||% list()
  re <- res$random_effects
  list(
    model_type      = res$model_type_used %||% rs$model_type %||% "",
    transform       = res$transform_used %||% rs$transform %||% "",
    random_effects  = if (!is.null(re$used)) {
      if (identical(re$used, re$requested)) re$used
      else paste0(re$used, " (requested: ", re$requested, ")")
    } else rs$random_effects %||% "",
    reference_group = res$summary$data_description$reference_group %||%
                      rs$reference_group %||% "",
    cage_effect     = res$summary$model_specification$cage_placement %||%
                      rs$cage_effect %||% "",
    comparisons     = if (!is.null(res$comparison_family)) {
      paste0(res$comparison_family, ", ", pretty_adjust(res$p_adjust_method_used))
    } else "",
    zero_floor      = trimws(paste(zero_floor_line(res), collapse = "")),
    n_rows          = rs$n_rows %||% NA
  )
}

